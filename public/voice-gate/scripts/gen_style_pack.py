"""Generate the VoiceGate Vale style from rules.py.

The pack is an artifact, not a second rule list: every token comes from the
engine's own families, so a word added to ``rules.py`` reaches Vale by running
this script. ``tests/test_style_pack.py`` regenerates into a temp directory and
diffs the result, so a stale pack fails instead of drifting.

Vale 3.x has no ``raw`` rule type, so every rule is ``existence`` with an
explicit scope.

Run from the plugin directory:

    python scripts/gen_style_pack.py
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path
from typing import Any, Dict, List

HERE = Path(__file__).resolve().parent.parent
STYLE = Path("styles") / "VoiceGate"

# family, file, level, message, scope
PACK = [
    ("buzzwords", "Terms.yml", "warning",
     "AI vocabulary: '%s'. Name the thing instead.", "sentence"),
    ("marketing_adjectives", "Marketing.yml", "warning",
     "Promotional adjective: '%s'. Say what it does.", "sentence"),
    ("significance_inflation", "Significance.yml", "warning",
     "Inflated significance: '%s'. State what happened.", "sentence"),
    ("conclusion_signposts", "Signposts.yml", "warning",
     "Conclusion signpost: '%s'. End on the point.", "sentence"),
    ("cliche_openers", "Openers.yml", "warning",
     "Cliché opener: '%s'. Start with the subject.", "sentence"),
    ("hedges", "Hedges.yml", "suggestion",
     "Hedge: '%s'. Only hedge when the evidence is thin.", "sentence"),
    ("filler", "Filler.yml", "suggestion",
     "Wordy construction: '%s'.", "sentence"),
    ("transitions", "Transitions.yml", "suggestion",
     "Transition that announces structure: '%s'.", "sentence"),
]

NEGATION = """extends: existence
message: "Negation triad: 'not just X, but Y' frame."
level: warning
scope: sentence
nonword: true
tokens:
  - '(?i)\\bnot (?:just|only)\\b[^.!?]{0,90}\\bbut\\b'
"""

INI = """# Generated by scripts/gen_style_pack.py. Vale reads this file directly, so a
# repository can copy it and the styles directory to lint the same rules.
StylesPath = styles
MinAlertLevel = warning

[*.md]
BasedOnStyles = VoiceGate

[*.markdown]
BasedOnStyles = VoiceGate
"""


def _token_lines(values: List[str]) -> str:
    return "\n".join("  - " + json.dumps(value, ensure_ascii=False) for value in values)


def _existence(level: str, message: str, values: List[str], scope: str) -> str:
    return (
        "extends: existence\n"
        f"message: {json.dumps(message)}\n"
        f"level: {level}\n"
        f"scope: {scope}\n"
        "ignorecase: true\n"
        "nonword: false\n"
        "tokens:\n"
        + _token_lines(values)
        + "\n"
    )


def build(rules_module: Any) -> Dict[Path, str]:
    out: Dict[Path, str] = {}
    for family, filename, level, message, scope in PACK:
        out[STYLE / filename] = _existence(level, message, rules_module.BASE_RULES[family], scope)
    out[STYLE / "NegationTriad.yml"] = NEGATION
    out[Path(".vale.ini")] = INI
    return out


def main() -> int:
    spec = importlib.util.spec_from_file_location("vg_rules", HERE / "rules.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules["vg_rules"] = module
    spec.loader.exec_module(module)
    written = 0
    for path, text in build(module).items():
        target = HERE / path
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
            written += 1
            print(f"wrote {path}")
    print(f"{written} file(s) changed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
